"""Deterministic development provider.

**This provider does not call a language model.** It is a rule engine that reads
the structured request payload and returns schema-shaped output so that the whole
pipeline (prompt assembly -> structured output -> validation -> persistence ->
publication) can be developed, tested and demonstrated with no credentials and
no network.

Honesty requirements enforced by the rest of the system:

* ``is_mock`` is ``True``, so ``reviews.is_mock_provider`` is set and the UI
  displays a MOCK PROVIDER badge on every review it produces;
* every finding it returns carries ``provider="mock"`` and
  ``verification_status="ai_suggested"`` - never ``verified``;
* its heuristics are heuristics: nothing it returns is presented as a trained
  model's judgement.

Because it is deterministic it doubles as a reproducible baseline: given the same
diff and configuration it yields byte-identical output, which is what makes the
`static_heuristic` row in the evaluation reproducible.
"""

from __future__ import annotations

import ast
import re
from dataclasses import dataclass
from typing import Any

from patchlens.core.logging import get_logger
from patchlens.services.llm.base import (
    TASK_GENERATE_TEST,
    TASK_REVIEW_FINDINGS,
    LLMCompletion,
    LLMProvider,
    LLMRequest,
    LLMUsage,
)

logger = get_logger(__name__)

LONG_FUNCTION_LINES = 60
MANY_PARAMETERS = 6

_TODO_RE = re.compile(r"#\s*(TODO|FIXME|XXX|HACK)\b[:\s]*(.*)", re.IGNORECASE)
_PRINT_RE = re.compile(r"(?<![\w.])print\s*\(")
_RANGE_LEN_RE = re.compile(r"range\s*\(\s*len\s*\(")
_NONE_COMPARE_RE = re.compile(r"[!=]=\s*None\b|\bNone\s*[!=]=")
_TYPE_IGNORE_RE = re.compile(r"#\s*type:\s*ignore")


@dataclass(slots=True)
class _ChangedSymbolView:
    path: str
    qualified_name: str
    kind: str
    start_line: int
    end_line: int
    source: str
    signature: str | None
    docstring: str | None
    is_test: bool
    changed_lines: list[int]


def _empty_completion(request: LLMRequest, *, reason: str) -> LLMCompletion:
    payload: dict[str, Any] = {"findings": [], "notes": reason}
    return LLMCompletion(
        text=reason,
        provider="mock",
        model="deterministic-mock",
        is_mock=True,
        parsed=payload,
        usage=LLMUsage(),
        latency_ms=0,
        finish_reason="deterministic",
    )


class MockLLMProvider(LLMProvider):
    """Rule-based stand-in for an LLM; see the module docstring."""

    name = "mock"
    model = "deterministic-mock"
    is_mock = True

    def complete(self, request: LLMRequest) -> LLMCompletion:
        if request.task == TASK_REVIEW_FINDINGS:
            return self._review(request)
        if request.task == TASK_GENERATE_TEST:
            return self._generate_test(request)
        return _empty_completion(request, reason=f"mock provider has no handler for task {request.task!r}")

    # ---------------------------------------------------------------- review
    def _review(self, request: LLMRequest) -> LLMCompletion:
        symbols = request.payload.get("changed_symbols") or []
        diff_excerpt = str(request.payload.get("diff_excerpt") or "")
        findings: list[dict[str, Any]] = []

        for raw_symbol in symbols:
            if not isinstance(raw_symbol, dict):
                continue
            view = self._view(raw_symbol)
            if view is None:
                continue
            findings.extend(self._maintainability_findings(view, diff_excerpt))

        findings = self._dedupe(findings)
        parsed = {
            "findings": findings[: int(request.payload.get("max_findings", 20))],
            "notes": (
                "Generated by the deterministic development provider (provider=mock). "
                "These are rule-based signals, not model reasoning."
            ),
        }
        return LLMCompletion(
            text=f"deterministic provider produced {len(parsed['findings'])} candidate findings",
            provider=self.name,
            model=self.model,
            is_mock=True,
            parsed=parsed,
            usage=LLMUsage(),
            latency_ms=0,
            finish_reason="deterministic",
        )

    def _view(self, raw: dict[str, Any]) -> _ChangedSymbolView | None:
        source = str(raw.get("source") or "")
        path = str(raw.get("path") or "")
        if not source or not path:
            return None
        changed_lines = [int(line) for line in raw.get("changed_lines") or [] if isinstance(line, int)]
        return _ChangedSymbolView(
            path=path,
            qualified_name=str(raw.get("qualified_name") or ""),
            kind=str(raw.get("kind") or "function"),
            start_line=int(raw.get("start_line") or 1),
            end_line=int(raw.get("end_line") or 1),
            source=source,
            signature=raw.get("signature") if isinstance(raw.get("signature"), str) else None,
            docstring=raw.get("docstring") if isinstance(raw.get("docstring"), str) else None,
            is_test=bool(raw.get("is_test")),
            changed_lines=changed_lines
            or list(range(int(raw.get("start_line") or 1), int(raw.get("end_line") or 1) + 1)),
        )

    def _maintainability_findings(self, view: _ChangedSymbolView, diff_excerpt: str) -> list[dict[str, Any]]:
        findings: list[dict[str, Any]] = []
        base_line = view.start_line

        for offset, line in enumerate(view.source.splitlines()):
            line_number = base_line + offset
            if line_number not in view.changed_lines:
                continue

            todo = _TODO_RE.search(line)
            if todo:
                findings.append(
                    self._finding(
                        rule_id="mock-unresolved-marker",
                        category="maintainability",
                        severity="low",
                        title=f"Unresolved {todo.group(1).upper()} marker added in {view.qualified_name}",
                        explanation=(
                            f"The added line {line_number} introduces a `{todo.group(1).upper()}` marker"
                            + (f": {todo.group(2).strip()}" if todo.group(2).strip() else ".")
                            + " Deferred work attached to a pull request tends to be forgotten; link an issue or"
                            " resolve it before merge."
                        ),
                        path=view.path,
                        line=line_number,
                        evidence=[{"kind": "diff_line", "line": line_number, "excerpt": line.strip()[:200]}],
                    )
                )

            if not view.is_test and _PRINT_RE.search(line):
                findings.append(
                    self._finding(
                        rule_id="mock-print-statement",
                        category="maintainability",
                        severity="low",
                        title=f"Debug print added in {view.qualified_name}",
                        explanation=(
                            f"Line {line_number} writes to stdout. Library code should use the `logging`"
                            " module so callers control verbosity and structured output."
                        ),
                        path=view.path,
                        line=line_number,
                        evidence=[{"kind": "diff_line", "line": line_number, "excerpt": line.strip()[:200]}],
                    )
                )

            if _RANGE_LEN_RE.search(line):
                findings.append(
                    self._finding(
                        rule_id="mock-range-len-iteration",
                        category="style",
                        severity="low",
                        title="Index iteration over a sequence in changed code",
                        explanation=(
                            f"Line {line_number} iterates with `range(len(...))`. Iterating the object itself,"
                            " or `enumerate`/`zip`, is usually clearer and avoids index bugs."
                        ),
                        path=view.path,
                        line=line_number,
                        evidence=[{"kind": "diff_line", "line": line_number, "excerpt": line.strip()[:200]}],
                    )
                )

            if _NONE_COMPARE_RE.search(line) and "is None" not in line and "is not None" not in line:
                findings.append(
                    self._finding(
                        rule_id="mock-none-comparison",
                        category="style",
                        severity="low",
                        title="Equality comparison against None in changed code",
                        explanation=(
                            f"Line {line_number} compares with `==`/`!=` against `None`."
                            " Identity comparison (`is None`) is the idiomatic and more robust form."
                        ),
                        path=view.path,
                        line=line_number,
                        evidence=[{"kind": "diff_line", "line": line_number, "excerpt": line.strip()[:200]}],
                    )
                )

            if _TYPE_IGNORE_RE.search(line):
                findings.append(
                    self._finding(
                        rule_id="mock-type-ignore",
                        category="maintainability",
                        severity="info",
                        title="New `# type: ignore` suppressions",
                        explanation=(
                            f"Line {line_number} suppresses type checking. If the underlying type is wrong,"
                            " fixing it keeps future errors visible; if it is genuinely unimplementable,"
                            " an unqualified `type: ignore` hides every error on that line."
                        ),
                        path=view.path,
                        line=line_number,
                        evidence=[{"kind": "diff_line", "line": line_number, "excerpt": line.strip()[:200]}],
                    )
                )

        body_lines = view.end_line - view.start_line + 1
        if body_lines > LONG_FUNCTION_LINES and not view.is_test:
            findings.append(
                self._finding(
                    rule_id="mock-long-function",
                    category="maintainability",
                    severity="low",
                    title=f"{view.qualified_name} grew to {body_lines} lines",
                    explanation=(
                        f"`{view.qualified_name}` spans {body_lines} lines after this change. Long functions are"
                        " harder to test and review; consider extracting cohesive helpers. This is a size signal,"
                        " not a correctness claim."
                    ),
                    path=view.path,
                    line=view.start_line,
                    evidence=[
                        {
                            "kind": "symbol",
                            "symbol": view.qualified_name,
                            "start_line": view.start_line,
                            "end_line": view.end_line,
                            "lines": body_lines,
                        }
                    ],
                )
            )

        parameter_count = self._parameter_count(view)
        if parameter_count is not None and parameter_count > MANY_PARAMETERS and not view.is_test:
            findings.append(
                self._finding(
                    rule_id="mock-too-many-parameters",
                    category="maintainability",
                    severity="low",
                    title=f"{view.qualified_name} takes {parameter_count} parameters",
                    explanation=(
                        f"The signature has {parameter_count} parameters. Wide signatures are easy to call"
                        " incorrectly (particularly with several same-typed arguments) and usually signal a"
                        " missing value object."
                    ),
                    path=view.path,
                    line=view.start_line,
                    evidence=[{"kind": "symbol", "symbol": view.qualified_name, "signature": view.signature}],
                )
            )

        if (
            not view.docstring
            and not view.is_test
            and view.kind in {"function", "class"}
            and not view.qualified_name.startswith("_")
        ):
            findings.append(
                self._finding(
                    rule_id="mock-missing-docstring",
                    category="maintainability",
                    severity="info",
                    title=f"Public {view.kind} `{view.qualified_name}` has no docstring",
                    explanation=(
                        f"`{view.qualified_name}` is public API in {view.path} and is not documented. A one-line"
                        " docstring stating inputs, side effects and raised exceptions is usually enough."
                    ),
                    path=view.path,
                    line=view.start_line,
                    evidence=[{"kind": "symbol", "symbol": view.qualified_name, "signature": view.signature}],
                )
            )

        return findings

    @staticmethod
    def _parameter_count(view: _ChangedSymbolView) -> int | None:
        if not view.signature:
            return None
        try:
            module = ast.parse(f"{view.signature}:\n    pass\n")
        except SyntaxError:
            return None
        node = module.body[0]
        if not isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
            return None
        args = node.args
        total = len(args.posonlyargs) + len(args.args) + len(args.kwonlyargs)
        if args.vararg is not None:
            total += 1
        if args.kwarg is not None:
            total += 1
        return total

    @staticmethod
    def _finding(
        *,
        rule_id: str,
        category: str,
        severity: str,
        title: str,
        explanation: str,
        path: str,
        line: int,
        evidence: list[dict[str, Any]],
    ) -> dict[str, Any]:
        return {
            "rule_id": rule_id,
            "category": category,
            "severity": severity,
            "title": title,
            "explanation": explanation,
            "path": path,
            "start_line": line,
            "end_line": line,
            "evidence": evidence,
            "suggestion": None,
            "confidence": None,
        }

    @staticmethod
    def _dedupe(findings: list[dict[str, Any]]) -> list[dict[str, Any]]:
        seen: set[tuple[str, str, int]] = set()
        unique: list[dict[str, Any]] = []
        for finding in findings:
            key = (str(finding.get("rule_id")), str(finding.get("path")), int(finding.get("start_line") or 0))
            if key in seen:
                continue
            seen.add(key)
            unique.append(finding)
        return unique

    # -------------------------------------------------------- test generation
    def _generate_test(self, request: LLMRequest) -> LLMCompletion:
        payload = request.payload
        target_path = str(payload.get("target_path") or "module.py")
        symbol = str(payload.get("target_symbol") or "target")
        signature = str(payload.get("signature") or f"def {symbol}(...):")
        test_path = str(payload.get("test_path") or "tests/test_generated.py")
        module_name = str(payload.get("module_name") or target_path.replace("/", ".").removesuffix(".py"))
        example = payload.get("example_call") or {}
        call_args = str(example.get("call") if isinstance(example, dict) else "") or f"{symbol}()"

        body = [
            '"""Regression test generated by the deterministic development provider.',
            "",
            "Provider: mock (rule-based). This test has NOT been executed unless its run",
            "status in PatchLens says so; generation alone is not verification.",
            '"""',
            "",
            "from __future__ import annotations",
            "",
            "import inspect",
            "",
            "import pytest",
            "",
            f"from {module_name.split('.')[0]} import {module_name.split('.')[-1]}  # noqa: F401  (adjust import to your package)",
            "",
            "",
            "def test_target_is_importable_and_callable() -> None:",
            f'    """The changed symbol {symbol} must exist and be callable."""',
            f"    assert callable(getattr({module_name.split('.')[-1]}, {symbol.split('.')[-1]!r}))",
            "",
            "",
            "def test_signature_is_stable() -> None:",
            f'    """Guard the public signature of {symbol} against accidental change."""',
            f"    signature = str(inspect.signature({module_name.split('.')[-1]}.{symbol.split('.')[-1]}))",
            "    assert signature  # non-empty; tighten with the expected parameter list",
            "",
            "",
            "def test_regression_placeholder() -> None:",
            '    """TODO(developer): assert the specific behaviour changed in this pull request."""',
            "    with pytest.raises(AssertionError):",
            "        assert False, 'replace this placeholder with the real regression assertion'",
            "",
            f"# Reference call shape observed for {symbol}({signature.split('(', 1)[-1]})",
            f"# example: {call_args}",
        ]
        source = "\n".join(body) + "\n"
        parsed = {
            "test_path": test_path,
            "test_source": source,
            "rationale": (
                f"Deterministic placeholder suite for {symbol}: importability, signature stability and a"
                " regression placeholder the developer must fill in. No claim is made that these tests pass."
            ),
        }
        return LLMCompletion(
            text=source,
            provider=self.name,
            model=self.model,
            is_mock=True,
            parsed=parsed,
            usage=LLMUsage(),
            latency_ms=0,
            finish_reason="deterministic",
        )


__all__ = ["MockLLMProvider"]
