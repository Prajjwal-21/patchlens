"""Repository file discovery.

Decides *what* PatchLens is willing to read from a checkout. Everything here is
defensive: repository contents are untrusted, paths may escape the root via
symlinks, and large or binary files must never reach the parser or a model
prompt.
"""

from __future__ import annotations

import fnmatch
import os
from dataclasses import dataclass, field
from pathlib import Path

from patchlens.core.config import Settings, get_settings
from patchlens.core.logging import get_logger
from patchlens.core.security import sha256_hex

logger = get_logger(__name__)

PYTHON_SUFFIXES = (".py", ".pyi")

#: Markers that identify machine-generated files worth skipping.
_GENERATED_MARKERS = (
    "@generated",
    "code generated by",
    "auto-generated",
    "autogenerated",
    "do not edit",
    "this file is generated",
)

#: Names that frequently contain credentials; never indexed even if *.py-shaped.
_NEVER_INDEX_NAMES = {".env", "credentials", "secrets", "id_rsa", "id_ed25519"}

_IGNORE_FILE = ".patchlensignore"


@dataclass(frozen=True, slots=True)
class DiscoveredFile:
    """A file selected for parsing, with cheap invariants already checked."""

    path: str
    """POSIX relative path from the repository root (safe, validated by caller)."""
    size_bytes: int
    content_hash: str
    text: str
    lines: int
    looks_like_test: bool


@dataclass(slots=True)
class DiscoveryReport:
    """Aggregate discovery outcome, persisted for the UI and diagnostics."""

    files: list[DiscoveredFile] = field(default_factory=list)
    skipped: dict[str, int] = field(default_factory=dict)
    scanned: int = 0
    total_bytes: int = 0

    def skip(self, reason: str) -> None:
        self.skipped[reason] = self.skipped.get(reason, 0) + 1

    @property
    def file_count(self) -> int:
        return len(self.files)

    @property
    def skipped_count(self) -> int:
        return sum(self.skipped.values())


def load_ignore_patterns(root: Path) -> list[str]:
    """Read optional ``.patchlensignore`` glob patterns (one per line)."""
    ignore_path = root / _IGNORE_FILE
    if not ignore_path.is_file():
        return []
    try:
        raw = ignore_path.read_text(encoding="utf-8", errors="replace")
    except OSError:  # pragma: no cover - unreadable file
        return []
    patterns: list[str] = []
    for line in raw.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#"):
            patterns.append(stripped)
    return patterns


def is_test_path(relative_path: str) -> bool:
    """Heuristic test detection: directory name, or ``test_*.py`` / ``*_test.py``."""
    parts = Path(relative_path).parts
    if any(part in {"tests", "test", "testing"} for part in parts[:-1]):
        return True
    name = parts[-1]
    return name.startswith("test_") or name.endswith("_test.py") or name == "conftest.py"


def _is_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:5]).lower()
    return any(marker in head for marker in _GENERATED_MARKERS)


def _looks_binary(chunk: bytes) -> bool:
    return b"\x00" in chunk


class RepositoryWalker:
    """Walks a checkout and yields indexable Python files."""

    def __init__(self, settings: Settings | None = None) -> None:
        self.settings = settings or get_settings()
        self._allowed = tuple(self.settings.allowed_file_extensions or PYTHON_SUFFIXES)
        self._excluded_dirs = set(self.settings.excluded_dir_names)
        self._excluded_patterns = list(self.settings.excluded_file_patterns)

    def walk(self, root: Path, *, on_progress: object | None = None) -> DiscoveryReport:
        """Discover files under ``root``.

        Never follows symbolic links out of the tree, never reads more than
        ``INDEX_MAX_FILE_BYTES`` per file and never reads a path that fails the
        containment check.
        """
        report = DiscoveryReport()
        root = root.resolve()
        if not root.is_dir():
            raise NotADirectoryError(f"not a directory: {root}")

        root_real = os.path.realpath(root)
        patterns = self._excluded_patterns + load_ignore_patterns(root)
        stack: list[Path] = [root]
        budget = self.settings.max_index_snapshot_bytes

        while stack:
            current = stack.pop()
            try:
                entries = sorted(os.scandir(current), key=lambda entry: entry.name)
            except (PermissionError, FileNotFoundError) as exc:
                logger.warning("skipping unreadable directory %s (%s)", current, type(exc).__name__)
                report.skip("unreadable_directory")
                continue

            for entry in entries:
                report.scanned += 1
                if report.file_count >= self.settings.index_max_files:
                    report.skip("file_limit_reached")
                    break

                if entry.is_symlink():
                    target = os.path.realpath(entry.path)
                    if not target.startswith(root_real):
                        report.skip("symlink_escape")
                        continue

                if entry.is_dir(follow_symlinks=False):
                    if entry.name in self._excluded_dirs or entry.name.startswith("."):
                        report.skip("excluded_directory")
                        continue
                    stack.append(Path(entry.path))
                    continue

                if not entry.is_file(follow_symlinks=True):
                    continue

                selected = self._select(entry, root, patterns, report, budget)
                if selected is None:
                    continue
                budget -= selected.size_bytes
                report.files.append(selected)
                report.total_bytes += selected.size_bytes

        report.files.sort(key=lambda item: item.path)
        return report

    # ----------------------------------------------------------------- internals
    def _select(
        self,
        entry: os.DirEntry[str],
        root: Path,
        patterns: list[str],
        report: DiscoveryReport,
        budget: int,
    ) -> DiscoveredFile | None:
        name = entry.name
        if name.lower() in _NEVER_INDEX_NAMES or name.startswith(".env"):
            report.skip("secret_like_filename")
            return None
        if Path(name).suffix.lower() not in self._allowed:
            report.skip("unsupported_extension")
            return None
        if entry.name.startswith("."):
            report.skip("hidden_file")
            return None

        relative = Path(entry.path).relative_to(root).as_posix()
        if self._matches_pattern(relative, patterns):
            report.skip("ignore_pattern")
            return None

        try:
            size = entry.stat(follow_symlinks=True).st_size
        except OSError:
            report.skip("stat_failed")
            return None

        if size == 0:
            report.skip("empty_file")
            return None
        if size > self.settings.index_max_file_bytes:
            report.skip("file_too_large")
            return None
        if budget - size < 0:
            report.skip("snapshot_budget_exhausted")
            return None

        try:
            with Path(entry.path).open("rb") as handle:
                raw = handle.read(self.settings.index_max_file_bytes + 1)
        except OSError:
            report.skip("read_failed")
            return None

        if _looks_binary(raw[:4096]):
            report.skip("binary_file")
            return None

        text = raw.decode("utf-8", errors="replace")
        if _is_generated(text):
            report.skip("generated_file")
            return None

        return DiscoveredFile(
            path=relative,
            size_bytes=len(raw),
            content_hash=sha256_hex(raw),
            text=text,
            lines=text.count("\n") + 1,
            looks_like_test=is_test_path(relative),
        )

    @staticmethod
    def _matches_pattern(relative: str, patterns: list[str]) -> bool:
        for pattern in patterns:
            if fnmatch.fnmatch(relative, pattern) or fnmatch.fnmatch(Path(relative).name, pattern):
                return True
        return False


def compute_tree_hash(report: DiscoveryReport) -> str:
    """Stable hash of the file set: lets the indexer detect no-op reindexes."""
    return sha256_hex("\n".join(f"{item.path}:{item.content_hash}" for item in report.files).encode("utf-8"))


